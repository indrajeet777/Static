#include "NormalCalculator.h"

double NormalCalculator::add(double a, double b) const { return a + b; }
double NormalCalculator::subtract(double a, double b) const { return a - b; }
double NormalCalculator::multiply(double a, double b) const { return a * b; }
double NormalCalculator::divide(double a, double b) const { return a / b; }
