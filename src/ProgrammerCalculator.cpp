#include "ProgrammerCalculator.h"

double ProgrammerCalculator::add(double a, double b) const { return a + b; }
double ProgrammerCalculator::subtract(double a, double b) const { return a - b; }
double ProgrammerCalculator::multiply(double a, double b) const { return a * b; }
double ProgrammerCalculator::divide(double a, double b) const { return a / b; }
int ProgrammerCalculator::bitwiseAnd(int a, int b) const { return a & b; }
int ProgrammerCalculator::bitwiseOr(int a, int b) const { return a | b; }
int ProgrammerCalculator::bitwiseXor(int a, int b) const { return a ^ b; }
